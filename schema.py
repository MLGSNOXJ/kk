from datetime import datetime
from pydantic import BaseModel


# Модель для представления пользователя в ответах API
class UserGet(BaseModel):
    """
    Модель данных пользователя для API-ответов.
    """

    id: int  # Уникальный идентификатор пользователя
    gender: int  # Пол пользователя (числовой код)
    age: int  # Возраст пользователя
    country: str  # Страна проживания
    city: str  # Город проживания
    exp_group: int  # Экспериментальная группа пользователя
    os: str  # Операционная система устройства пользователя
    source: str  # Источник регистрации или привлечения пользователя


# Модель для представления поста в ответах API
class PostGet(BaseModel):
    """
    Модель данных поста для API-ответов.
    """

    id: int  # Уникальный идентификатор поста
    text: str  # Текстовое содержимое поста
    topic: str  # Тематика или категория поста


# Модель для представления действия пользователя с постом в ответах API
class FeedGet(BaseModel):
    """
    Модель данных действия пользователя с постом для API-ответов.
    """

    user_id: int  # Идентификатор пользователя, совершившего действие
    post_id: int  # Идентификатор поста, с которым связано действие

    # Вложенный объект с подробной информацией о пользователе.
    # Вместо простого ID мы передаём полноценный объект UserGet,
    # что позволяет клиенту получить все необходимые данные о пользователе сразу.
    user: UserGet

    # Вложенный объект с подробной информацией о посте.
    # Аналогично пользователю, здесь передаётся полный объект PostGet,
    # чтобы клиент видел не только ID поста, но и его содержимое и тему.
    post: PostGet

    action: str  # Тип действия (например, 'like', 'view')
    time: datetime  # Время совершения действия
